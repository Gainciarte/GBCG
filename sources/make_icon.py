"""
Generates the GBCG launcher icon from a single description of its shapes:
the front of a grey handheld filling the whole icon, with a "G" on the screen.

The console body is the adaptive icon's background layer, so it takes the
launcher's mask shape (circle, squircle...) and fills the icon edge to edge.
The screen and controls are the foreground layer.

Writes, relative to the repository root:
  app/src/main/res/drawable/ic_launcher_background.xml   (adaptive icon)
  app/src/main/res/drawable/ic_launcher_foreground.xml   (adaptive icon)
  app/src/main/res/drawable/ic_launcher_monochrome.xml   (themed icon, Android 13+)
  app/src/main/res/mipmap-*/ic_launcher(_round).png      (Android 7 and below)
  app/src/main/ic_launcher-playstore.png                 (512x512, store listing)
  sources/ic_launcher_gbcg.svg                           (preview / editing)

Usage: python sources/make_icon.py   (needs Pillow)
To change the look, edit the colours and coordinates below and run it again.
"""
import math
import os
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "app", "src", "main", "res")

# Colours
BODY = "#B9BCC2"
BEZEL = "#3D4450"
SCREEN = "#A7C957"
LETTER = "#2E4A1E"
CONTROLS = "#33373D"

# Geometry, in the 108x108 adaptive icon viewport. Launchers may mask
# everything outside the central circle of diameter 66 (radius 33 around
# 54,54), so every shape below stays inside it.
BEZEL_RECT = (33, 29, 42, 29, 4)         # x, y, width, height, corner radius
SCREEN_RECT = (41, 32, 26, 23.4, 1)      # 10:9, like the original screen
LETTER_CENTRE = (54, 43.7)
LETTER_RADIUS = 6.6
LETTER_STROKE = 3.2
LETTER_OPENING = 45                      # degrees of the gap above the bar
DPAD_CENTRE = (40.5, 69)
DPAD_ARM = 6                             # half the length of each arm
DPAD_HALF_WIDTH = 2.1
BUTTON_B = (63.5, 72, 3.6)               # x, y, radius
BUTTON_A = (71.5, 67, 3.6)
SELECT_RECT = (45.5, 78.5, 6, 2.2, 1.1)
START_RECT = (56.5, 78.5, 6, 2.2, 1.1)


def rounded_rect_path(x, y, w, h, r):
    return (f"M{x + r:g},{y:g} h{w - 2 * r:g} a{r:g},{r:g} 0 0 1 {r:g},{r:g} v{h - 2 * r:g} "
            f"a{r:g},{r:g} 0 0 1 {-r:g},{r:g} h{-(w - 2 * r):g} a{r:g},{r:g} 0 0 1 {-r:g},{-r:g} "
            f"v{-(h - 2 * r):g} a{r:g},{r:g} 0 0 1 {r:g},{-r:g} z")


def circle_path(cx, cy, r):
    return f"M{cx - r:g},{cy:g} a{r:g},{r:g} 0 1 0 {2 * r:g},0 a{r:g},{r:g} 0 1 0 {-2 * r:g},0 z"


def dpad_points():
    cx, cy = DPAD_CENTRE
    a, w = DPAD_ARM, DPAD_HALF_WIDTH
    return [(cx - w, cy - a), (cx + w, cy - a), (cx + w, cy - w), (cx + a, cy - w),
            (cx + a, cy + w), (cx + w, cy + w), (cx + w, cy + a), (cx - w, cy + a),
            (cx - w, cy + w), (cx - a, cy + w), (cx - a, cy - w), (cx - w, cy - w)]


def dpad_path():
    return "M" + " L".join(f"{x:g},{y:g}" for x, y in dpad_points()) + " z"


def letter_points():
    """Start of the arc (upper right), end of the arc (right) and end of the bar."""
    cx, cy = LETTER_CENTRE
    r = LETTER_RADIUS
    a = math.radians(-LETTER_OPENING)
    start = (cx + r * math.cos(a), cy + r * math.sin(a))
    end = (cx + r, cy)
    bar_end = (cx + 0.6, cy)
    return start, end, bar_end


def letter_path():
    # The long way round from the upper right to the right, then the bar
    (sx, sy), (ex, ey), (bx, by) = letter_points()
    r = LETTER_RADIUS
    return f"M{sx:.2f},{sy:.2f} A{r:g},{r:g} 0 1 0 {ex:g},{ey:g} L{bx:g},{by:g}"


def vector(paths):
    body = "\n".join(paths)
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by sources/make_icon.py: edit that script instead. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="108dp"\n    android:height="108dp"\n'
            '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
            f"{body}\n</vector>\n")


def vpath(data, colour, even_odd=False):
    extra = '\n      android:fillType="evenOdd"' if even_odd else ""
    return (f'  <path\n      android:pathData="{data}"\n'
            f'      android:fillColor="{colour}"{extra} />')


def vstroke(data, colour, width):
    return (f'  <path\n      android:pathData="{data}"\n'
            f'      android:strokeColor="{colour}"\n'
            f'      android:strokeWidth="{width}"\n'
            '      android:strokeLineCap="round"\n'
            '      android:strokeLineJoin="round" />')


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def controls(colour):
    return [
        vpath(dpad_path(), colour),
        vpath(circle_path(*BUTTON_B), colour),
        vpath(circle_path(*BUTTON_A), colour),
        vpath(rounded_rect_path(*SELECT_RECT), colour),
        vpath(rounded_rect_path(*START_RECT), colour),
    ]


def foreground_paths():
    return [
        vpath(rounded_rect_path(*BEZEL_RECT), BEZEL),
        vpath(rounded_rect_path(*SCREEN_RECT), SCREEN),
        vstroke(letter_path(), LETTER, LETTER_STROKE),
    ] + controls(CONTROLS)


def monochrome_paths():
    # The bezel as a frame around the screen (even-odd fill), the letter and the controls
    white = "#FFFFFFFF"
    frame = rounded_rect_path(*BEZEL_RECT) + " " + rounded_rect_path(*SCREEN_RECT)
    return [vpath(frame, white, even_odd=True), vstroke(letter_path(), white, LETTER_STROKE)] + controls(white)


def render(size, crop=(18, 90), mask=None):
    """Renders the icon at size x size pixels, showing the viewport range crop."""
    ss = 4
    lo, hi = crop
    scale = size * ss / (hi - lo)

    def tr(x, y):
        return ((x - lo) * scale, (y - lo) * scale)

    img = Image.new("RGBA", (size * ss, size * ss), BODY)
    d = ImageDraw.Draw(img)

    def rrect(rect, fill):
        x, y, w, h, r = rect
        d.rounded_rectangle([tr(x, y), tr(x + w, y + h)], radius=r * scale, fill=fill)

    def circle(cx, cy, r, fill):
        d.ellipse([tr(cx - r, cy - r), tr(cx + r, cy + r)], fill=fill)

    rrect(BEZEL_RECT, BEZEL)
    rrect(SCREEN_RECT, SCREEN)

    # The letter: an arc and a bar with round ends
    cx, cy = LETTER_CENTRE
    r, w = LETTER_RADIUS, LETTER_STROKE
    (sx, sy), (ex, ey), (bx, by) = letter_points()
    box = [tr(cx - r - w / 2, cy - r - w / 2), tr(cx + r + w / 2, cy + r + w / 2)]
    d.arc(box, start=0, end=360 - LETTER_OPENING, fill=LETTER, width=round(w * scale))
    d.line([tr(ex, ey), tr(bx, by)], fill=LETTER, width=round(w * scale))
    for px, py in ((sx, sy), (ex, ey), (bx, by)):
        circle(px, py, w / 2, LETTER)

    d.polygon([tr(x, y) for x, y in dpad_points()], fill=CONTROLS)
    circle(*BUTTON_B, CONTROLS)
    circle(*BUTTON_A, CONTROLS)
    rrect(SELECT_RECT, CONTROLS)
    rrect(START_RECT, CONTROLS)

    if mask is not None:
        m = Image.new("L", img.size, 0)
        md = ImageDraw.Draw(m)
        full = [(0, 0), (img.size[0] - 1, img.size[1] - 1)]
        if mask == "round":
            md.ellipse(full, fill=255)
        else:
            md.rounded_rectangle(full, radius=img.size[0] * 0.18, fill=255)
        img.putalpha(m)
    return img.resize((size, size), Image.LANCZOS)


def svg():
    def rect(r, fill):
        x, y, w, h, rad = r
        return f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="{rad}" fill="{fill}"/>'

    def circ(c, fill):
        return f'<circle cx="{c[0]}" cy="{c[1]}" r="{c[2]}" fill="{fill}"/>'

    pts = " ".join(f"{x:g},{y:g}" for x, y in dpad_points())
    return "\n".join([
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108" width="432" height="432">',
        "<!-- Generated by make_icon.py -->",
        f'<rect width="108" height="108" fill="{BODY}"/>',
        rect(BEZEL_RECT, BEZEL), rect(SCREEN_RECT, SCREEN),
        f'<path d="{letter_path()}" fill="none" stroke="{LETTER}" stroke-width="{LETTER_STROKE}" '
        'stroke-linecap="round" stroke-linejoin="round"/>',
        f'<polygon points="{pts}" fill="{CONTROLS}"/>',
        circ(BUTTON_B, CONTROLS), circ(BUTTON_A, CONTROLS),
        rect(SELECT_RECT, CONTROLS), rect(START_RECT, CONTROLS),
        "</svg>", ""])


def main():
    drawable = os.path.join(RES, "drawable")
    write(os.path.join(drawable, "ic_launcher_background.xml"),
          vector([vpath("M0,0h108v108h-108z", BODY)]))
    write(os.path.join(drawable, "ic_launcher_foreground.xml"), vector(foreground_paths()))
    write(os.path.join(drawable, "ic_launcher_monochrome.xml"), vector(monochrome_paths()))

    # Legacy icons show the central 72x72 of the adaptive icon, pre-masked
    for density, size in {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}.items():
        folder = os.path.join(RES, f"mipmap-{density}")
        render(size, mask="square").save(os.path.join(folder, "ic_launcher.png"))
        render(size, mask="round").save(os.path.join(folder, "ic_launcher_round.png"))

    # The store applies its own mask to a full-bleed square
    render(512).convert("RGB").save(os.path.join(ROOT, "app", "src", "main", "ic_launcher-playstore.png"))
    write(os.path.join(ROOT, "sources", "ic_launcher_gbcg.svg"), svg())


if __name__ == "__main__":
    main()
